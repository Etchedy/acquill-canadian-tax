"""Generate worker/src/pages.js from the Python server's public pages, so both servers show the same text.

The hosted (Cloudflare) copy differs in one paragraph: where upstream requests are cached. Run after changing
public_pages.py:  python scripts/build_worker_pages.py
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
CONTACT = 'CONTACT@PLACEHOLDER.INVALID'
os.environ['SUPPORT_EMAIL'] = CONTACT
os.environ['PUBLIC_URL'] = 'https://placeholder.invalid'
from canadian_tax_mcp import public_pages  # noqa: E402

CACHE_LOCAL = ('<p>The application stores a local index of public CRA content. It does not intentionally persist users\' tool arguments '
               'or conversations. An in-memory cache holds upstream request parameters and responses; entries stop being reused after '
               'their TTL, normally one hour (30 minutes for official statutory sections), and are removed on later eviction or process '
               'restart. This is not a promise of immediate deletion at expiry.</p>')
CACHE_HOSTED = ('<p>The service is hosted on Cloudflare Workers and stores an index of public CRA content in Cloudflare D1. It does not '
                'intentionally persist users\' tool arguments or conversations. Upstream requests (including search terms sent to A2AJ) '
                'and their responses can be held in the Worker\'s memory and Cloudflare\'s cache for up to one hour (30 minutes for '
                'official statutory sections) so repeated requests are not re-sent. This is not a promise of immediate deletion at expiry.</p>')

pages = {}
for name in ('home', 'docs', 'privacy', 'terms', 'support'):
    page = public_pages.render(name)
    if name == 'privacy':
        assert CACHE_LOCAL in page, 'privacy text changed: update CACHE_LOCAL'
        page = page.replace(CACHE_LOCAL, CACHE_HOSTED)
    pages[name] = page
home = pages['home']
start, end = home.index('<h1>'), home.index('</main>')
pages['not_found'] = home[:start] + '<h1>Page not found</h1><p>See <a href="/docs">Documentation</a>. The MCP endpoint is <code>/mcp</code>.</p>' + home[end:]
pages['not_found'] = pages['not_found'].replace('<title>Canadian tax sources, together', '<title>Page not found')

out = ROOT / 'worker' / 'src' / 'pages.js'
out.write_text(f'''// Generated by scripts/build_worker_pages.py from src/canadian_tax_mcp/public_pages.py. Do not edit by hand.
const PAGES = {json.dumps(pages, indent=1, ensure_ascii=False)};
const CONTACT = {json.dumps(CONTACT)};
const DRAFT = '<p><strong>Development preview. This service is not publicly launched.</strong></p>';
const escape = s => s.replace(/[&<>"']/g, c => ({{'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#x27;'}})[c]);

export function render(page, {{ contact = '', live = false }} = {{}}) {{
  let html = PAGES[page];
  if (contact) html = html.split(CONTACT).join(escape(contact));
  else html = html.split(`<a href="mailto:${{CONTACT}}">${{CONTACT}}</a>`).join('Support contact not yet configured.');
  if (!(contact && live)) html = html.replace('<main>', '<main>' + DRAFT);
  return html;
}}
''', encoding='utf-8')
print('wrote', out.relative_to(ROOT), {k: len(v) for k, v in pages.items()})
